export const RTI_LANGS: RtiLang[] = [en, hi, bn, ta, te, mr, gu, kn, ml, pa, or, ur, as_, ne];
export const RTI_UNAVAILABLE = ["Bodo", "Dogri", "Kashmiri", "Konkani", "Maithili", "Manipuri", "Sanskrit", "Santali", "Sindhi"];

export interface RtiInput {
  lang: RtiLang;
  preset: PresetId | "custom";
  issue: string;
  period: string;
  constituency: string;
  state: string;
  name: string;
  address: string;
}

export function buildRti(i: RtiInput): string {
  const { lang: L } = i;
  const place = `${i.constituency} Lok Sabha constituency, ${i.state}`;
  const fill = (s: string) => s.replace("{place}", place).replace("{issue}", i.issue).replace("{period}", i.period).replace(/\{state\}/g, i.state);
  const lines = [
    L.to,
    fill(AUTHORITY[i.preset]),
    "",
    L.subject,
    "",
    L.sal,
    "",
    fill(L.intro),
    fill(L.topic),
    fill(L.period),
    "",
    ...L.items.map((t, n) => `${n + 1}. ${t}`),
    "",
    L.fee,
    L.transfer,
    "",
    L.close,
    "",
    `${L.name}: ${i.name || "______________________"}`,
    `${L.address}: ${i.address || "______________________"}`,
    `${L.date}: ${new Date().toLocaleDateString("en-GB")}`,
    `${L.sign}: ______________________`,
  ];
  return lines.join("\n");
}
